export default function SocialLinksBar({
  className = "",
  variant = "footer",
  showLabels = false
}: SocialLinksBarProps) {
  const isDark = variant === "dark" || variant === "footer";

  const getIcon = (id: string) => {
    switch (id) {
      case "instagram":
        return <SocialIcons.Instagram />;
      case "threads":
        return <SocialIcons.Threads />;
      case "x":
        return <SocialIcons.X />;
      case "tiktok":
        return <SocialIcons.TikTok />;
      case "facebook":
        return <SocialIcons.Facebook />;
      case "whatsapp":
        return <SocialIcons.WhatsApp />;
      default:
        return null;
    }
  };

  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {BRAND_CONTACTS.socials.map((social) => {
        return (
          <a
            key={social.id}
            href={social.url}
            target="_blank"
            rel="noopener noreferrer"
            title={`${social.name}: ${social.handle}`}
            aria-label={`${social.name} @alexfitnesshub`}
            className={`flex items-center gap-1.5 p-2 rounded-xl transition-all duration-200 border cursor-pointer select-none ${
              isDark
                ? "bg-slate-900/90 text-slate-300 border-slate-800 hover:border-slate-700 hover:text-white hover:bg-slate-800"
                : "bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-950 hover:bg-slate-50 shadow-xs"
            } ${social.color}`}
          >
            <div className="shrink-0">{getIcon(social.id)}</div>
            {showLabels && (
              <span className="text-xs font-bold tracking-tight">
                {social.name}
              </span>
            )}
          </a>
        );
      })}
    </div>
  );
}
