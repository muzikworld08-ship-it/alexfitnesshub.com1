export function getCuratedFallback(query: string, filter: string): CuratedWorkoutVideo[] {
  const lowerQ = (query || "").toLowerCase().trim();
  const lowerF = (filter || "").toLowerCase().trim();

  if (!lowerQ && !lowerF) {
    return CURATED_WORKOUT_VIDEOS;
  }

  let filtered = CURATED_WORKOUT_VIDEOS.filter((v) => {
    const matchesQ =
      !lowerQ ||
      v.title.toLowerCase().includes(lowerQ) ||
      v.channelTitle.toLowerCase().includes(lowerQ) ||
      v.description.toLowerCase().includes(lowerQ) ||
      v.tags.some((t) => t.toLowerCase().includes(lowerQ));

    const matchesF =
      !lowerF ||
      v.tags.some((t) => t.toLowerCase() === lowerF || lowerF.includes(t.toLowerCase()));

    return matchesQ && matchesF;
  });

  if (filtered.length === 0 && lowerQ) {
    filtered = CURATED_WORKOUT_VIDEOS.filter(
      (v) =>
        v.title.toLowerCase().includes(lowerQ) ||
        v.description.toLowerCase().includes(lowerQ) ||
        v.tags.some((t) => t.toLowerCase().includes(lowerQ))
    );
  }

  return filtered.length > 0 ? filtered : CURATED_WORKOUT_VIDEOS.slice(0, 8);
}
